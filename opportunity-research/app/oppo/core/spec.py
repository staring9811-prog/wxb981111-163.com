def default_draft(contract_code: str, fieldname: str, dtype: str) -> dict[str, str]:
    known = KNOWN_FIELDS.get((contract_code, fieldname))
    if known is None and contract_code == "C4":
        base = fieldname.removesuffix("证据状态")
        if fieldname.endswith("证据状态"):
            known = (f"{base}标签的证据状态（子体确认 / 父体回填 / 父体候选 / 信息不足 / 冲突）", "子体", "当月值", "人工标注", "按规则用", "类型属性缺子体值时用父体候选值并标“父体回填”；颜色、尺寸、盆数不回填")
        else:
            known = (f"属性标签：{base}", "子体", "当月值", "人工标注", "直接用", "")
    if known is None:
        known = ("约定外字段，含义待确认", "子体", "当月值", "平台实测", "回测不用", "")
    meaning, grain, timing, nature, usage, rule_text = known
    return {
        "meaning": meaning, "grain": grain, "timing": timing, "nature": nature, "usage": usage,
        "rule_text": rule_text, "dtype": dtype,
    }
